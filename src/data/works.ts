export interface Artwork {
  slug: string;
  title: string;
  year: number;
  medium: string | string[];
  dimensions?: string;
  description?: string;
  image: string;
  featured: boolean;
  group?: string;
}

export function mediumDisplay(medium: string | string[]): string {
  return Array.isArray(medium) ? medium.join(' & ') : medium;
}

export function mediumList(medium: string | string[]): string[] {
  return Array.isArray(medium) ? medium : [medium];
}

